#!/usr/bin/env python3
"""Generate bank domain catalogue from the Bank of Russia's public website table.

Usage: python3 tools/update_bank_sites.py downloaded-cowebsites.html
Source: https://www.cbr.ru/banking_sector/credit/cowebsites/
Only website hosts are included. Social network, app store and video hosts are
excluded because a bank's profile there does not make the whole host a bank site.
The result is a source snapshot, not a claim that these sites detect VPN.
"""

from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path
from urllib.parse import urlparse
from urllib.request import urlopen


EXCLUDED_HOSTS = {
    "vk.com", "vk.ru", "ok.ru", "odnoklassniki.ru", "max.ru", "t.me",
    "telegram.me", "telegram.org", "youtube.com", "youtu.be", "rutube.ru",
    "dzen.ru", "zen.yandex.ru", "twitter.com", "x.com", "facebook.com",
    "instagram.com", "linkedin.com", "tiktok.com", "pinterest.com",
    "rustore.ru", "play.google.com", "apps.apple.com", "appgallery.huawei.com",
    "market.yandex.ru", "store.steampowered.com",
}

OUTPUT = Path(__file__).resolve().parents[1] / (
    "apps/client/android/app/src/main/kotlin/com/example/nona_client/BankSites.kt"
)


def rows(source: str) -> list[tuple[str, list[str]]]:
    result = []
    for tr in re.findall(r"<tr\b[^>]*>(.*?)</tr>", source, re.I | re.S):
        cells = re.findall(r"<td\b[^>]*>(.*?)</td>", tr, re.I | re.S)
        if len(cells) != 4:
            continue
        name = html.unescape(re.sub(r"<[^>]*>", "", cells[2])).strip()
        links = re.findall(r'href="(https?://[^"]+)"', cells[3], re.I)
        if name and links:
            result.append((name, links))
    return result


def host_for(url: str) -> str | None:
    host = (urlparse(html.unescape(url)).hostname or "").lower().rstrip(".")
    if host.startswith("www."):
        host = host[4:]
    try:
        host = host.encode("idna").decode("ascii")
    except UnicodeError:
        return None
    if not re.fullmatch(r"[a-z0-9-]+(?:\.[a-z0-9-]+)+", host):
        return None
    if any(host == blocked or host.endswith("." + blocked) for blocked in EXCLUDED_HOSTS):
        return None
    return host


def catalogue(source: str) -> dict[str, str]:
    result: dict[str, str] = {}
    for bank, urls in rows(source):
        hosts = {host for url in urls if (host := host_for(url))}
        # A listed parent host covers its listed subdomains in Xray routing.
        for host in sorted(hosts):
            if any(host.endswith("." + parent) for parent in hosts if host != parent):
                continue
            result.setdefault(host, bank)
    return dict(sorted(result.items()))


def main() -> None:
    if len(sys.argv) > 2:
        raise SystemExit("usage: update_bank_sites.py [downloaded-cowebsites.html]")
    if len(sys.argv) == 2:
        source = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urlopen("https://www.cbr.ru/banking_sector/credit/cowebsites/", timeout=20) as response:
            source = response.read().decode("utf-8")
    dated = re.search(r"по состоянию на (\d{2}\.\d{2}\.\d{4})", source)
    if not dated:
        raise SystemExit("Bank of Russia publication date was not found")
    sites = catalogue(source)
    if len(rows(source)) < 300 or len(sites) < 300:
        raise SystemExit("Bank of Russia table is incomplete; output not changed")
    body = [
        "package com.example.nona_client",
        "",
        "// Generated by tools/update_bank_sites.py from the Bank of Russia's",
        f"// public credit-organisation website table, dated {dated.group(1)}.",
        "// Social-network and app-store profile hosts are omitted.",
        "internal object BankSites {",
        "    val domains: List<Pair<String, String>> = listOf(",
    ]
    body.extend(
        f"        {json.dumps(domain, ensure_ascii=False)} to {json.dumps(name, ensure_ascii=False)},"
        for domain, name in sites.items()
    )
    body.extend(["    )", "}", ""])
    OUTPUT.write_text("\n".join(body), encoding="utf-8")
    print(f"{len(rows(source))} credit organisations; {len(sites)} website hosts")


if __name__ == "__main__":
    main()
